"""Focused tests for the production license gate + build canary.

No network, no secrets: a fixed test secret mints vectors in-process, and one
known-good key below was generated by an independent implementation (Node.js
crypto) so the suite cross-checks the HMAC bytes, not just round-trips them.

NOTE: not yet run here (no Python interpreter in this environment). Run
``pytest tests/test_license.py`` where Python exists before trusting green.
"""

import json
import time

import pytest

from license_gate import (
    CANARY,
    LicenseError,
    enforce_license,
    is_production,
    issue_license_key,
    license_status,
    verify_license_key,
)

SECRET = "gridfork-test-secret-01"

# Independent vector: payload {"sub":"audit@example.com","exp":1893456000,
# "canary":CANARY}, HMAC-SHA256 under SECRET, computed with Node.js crypto.
KNOWN_GOOD_KEY = (
    "GF1.eyJzdWIiOiJhdWRpdEBleGFtcGxlLmNvbSIsImV4cCI6MTg5MzQ1NjAwMCwiY2FuYXJ5Ijoi"
    "R0YtQ0FOQVJZLWVkZDM4YmYwOGU0NDg5OTFlODM1NDkxNDc0MjA3MTRiIn0."
    "b47amltQDVCeTYItEy-z0LoVfaQmWBfvSPUh2HsrHTk"
)


def test_canary_shape():
    assert CANARY.startswith("GF-CANARY-") and len(CANARY) == 10 + 32


def test_issue_verify_roundtrip():
    key = issue_license_key(SECRET, "buyer@example.com", 30, now=1_700_000_000)
    payload = verify_license_key(key, SECRET, now=1_700_000_100)
    assert payload["sub"] == "buyer@example.com"
    assert payload["canary"] == CANARY


def test_known_good_vector_from_independent_implementation():
    payload = verify_license_key(KNOWN_GOOD_KEY, SECRET, now=1_700_000_000)
    assert payload == {
        "sub": "audit@example.com",
        "exp": 1893456000,
        "canary": CANARY,
    }


def test_tampered_signature_rejected():
    head, payload_b64, sig = KNOWN_GOOD_KEY.split(".")
    bad = f"{head}.{payload_b64}.{'A' * len(sig)}"
    with pytest.raises(LicenseError) as exc:
        verify_license_key(bad, SECRET, now=1_700_000_000)
    assert exc.value.code == "bad_signature"


def test_expired_rejected():
    key = issue_license_key(SECRET, "buyer@example.com", 1, now=1_700_000_000)
    with pytest.raises(LicenseError) as exc:
        verify_license_key(key, SECRET, now=1_700_000_000 + 2 * 86400)
    assert exc.value.code == "expired"


def test_wrong_canary_rejected():
    import base64
    import hashlib
    import hmac as hmac_mod
    import json

    payload = {"sub": "x@y.z", "exp": 1893456000, "canary": "GF-CANARY-" + "0" * 32}
    raw = base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":")).encode()).decode()
    sig = base64.urlsafe_b64encode(
        hmac_mod.new(SECRET.encode(), raw.encode(), hashlib.sha256).digest()
    ).decode()
    with pytest.raises(LicenseError) as exc:
        verify_license_key(f"GF1.{raw}.{sig}", SECRET, now=1_700_000_000)
    assert exc.value.code == "canary_mismatch"


def test_malformed_rejected():
    for bad in ["", "GF1.only", "GF1..", "XX.a.b", "GF1.%%%.%%%"]:
        with pytest.raises(LicenseError):
            verify_license_key(bad, SECRET, now=1_700_000_000)


def test_modes_and_enforcement(monkeypatch):
    monkeypatch.delenv("GRIDFORK_ENV", raising=False)
    monkeypatch.delenv("GRIDFORK_LICENSE_KEY", raising=False)
    assert is_production() is False
    assert enforce_license() is None  # evaluation is free

    monkeypatch.setenv("GRIDFORK_ENV", "production")
    assert is_production() is True
    with pytest.raises(LicenseError) as exc:
        enforce_license()
    assert exc.value.code == "missing"

    key = issue_license_key(SECRET, "prod@example.com", 365)
    monkeypatch.setenv("GRIDFORK_LICENSE_KEY", key)
    monkeypatch.setenv("GRIDFORK_LICENSE_SECRET", SECRET)
    payload = enforce_license()
    assert payload["sub"] == "prod@example.com"

    status = license_status()
    assert status["licensed"] is True and status["mode"] == "production"
    assert status["canary"] == CANARY
    assert SECRET not in json.dumps(status)  # secret never echoed
